"""GET-only transport adapter for this environment's intermittent Python TLS EOFs.
It enforces the paper executor's Binance public endpoint allowlist and does not alter
signals, costs, sizing, account state, or timestamps generated by paper10/run.py.
"""
import hashlib,json,subprocess,time,urllib.error,urllib.parse
from datetime import datetime,timezone
from email.message import Message
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
PUBLIC={'/api/v3/time','/api/v3/exchangeInfo','/api/v3/klines','/api/v3/avgPrice','/api/v3/ticker/bookTicker'}
def utc():return datetime.now(timezone.utc).isoformat().replace('+00:00','Z')
class Response:
 def __init__(self,body,status):
  self._body=body;self.status=status;self.headers=Message()
 def read(self):return self._body
 def __enter__(self):return self
 def __exit__(self,*args):return False
def urlopen(request,timeout=25):
 url=request.full_url;parsed=urllib.parse.urlsplit(url)
 if request.get_method()!='GET' or parsed.scheme!='https' or parsed.netloc!='data-api.binance.vision' or parsed.path not in PUBLIC:
  raise ValueError('curl transport denied non-allowlisted request')
 begun=utc();headers=[]
 for key,value in request.header_items():headers.extend(['-H',f'{key}: {value}'])
 marker=b'\n__PAPER10_HTTP_STATUS__'
 cmd=['curl','--silent','--show-error','--retry','5','--retry-all-errors','--retry-delay','1','--max-time',str(timeout),*headers,'--write-out','\n__PAPER10_HTTP_STATUS__%{http_code}',url]
 started=time.monotonic();proc=subprocess.run(cmd,stdout=subprocess.PIPE,stderr=subprocess.PIPE,timeout=timeout+10)
 ended=utc()
 if proc.returncode!=0:
  record={'url':url,'method':'GET','transport':'curl_public_allowlist','started_utc':begun,'ended_utc':ended,'elapsed_seconds':time.monotonic()-started,'curl_exit':proc.returncode,'error':proc.stderr.decode('utf-8','replace')[-1000:]}
  _record(record)
  raise urllib.error.URLError(record['error'])
 body,sep,tail=proc.stdout.rpartition(marker)
 if not sep:raise urllib.error.URLError('missing HTTP status marker from curl')
 try:status=int(tail.decode().strip())
 except ValueError as error:raise urllib.error.URLError('invalid HTTP status from curl') from error
 record={'url':url,'method':'GET','transport':'curl_public_allowlist','started_utc':begun,'received_utc':ended,'elapsed_seconds':time.monotonic()-started,'status':status,'response_sha256':hashlib.sha256(body).hexdigest(),'retry_policy':'curl --retry 5 --retry-all-errors;GET only'}
 _record(record)
 return Response(body,status)
def _record(record):
 roots=sorted((ROOT/'research/paper10/observations').glob('*'))
 if not roots:return
 folder=roots[-1];path=folder/'transport.jsonl'
 with path.open('a',encoding='utf-8')as out:out.write(json.dumps(record,ensure_ascii=False,separators=(',',':'))+'\n');out.flush()
